void Display(char ch)
{
    if (ch < 'A')
    {
        return;
    }

    Display(ch - 1);

    printf("%c\t", ch);

} // End of function

////////////////////////////////////////////////////////////////////////////////
//
//  Entry point function for the application
//
////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    char ch;

    printf("Enter the Number :\n");
    scanf("%d", &iValue);

    ch = 'A' + iValue;

    Display(ch);

    return 0;
} // End of main

