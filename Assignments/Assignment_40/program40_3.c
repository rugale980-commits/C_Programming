void Display(int iNo)
{
    if (iNo == 0)
    {
        return;
    }

    printf("%d\t", iNo);

    Display(iNo - 1);

} // End of function

////////////////////////////////////////////////////////////////////////////////
//
//  Entry point function for the application
//
////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter the Number :\n");
    scanf("%d", &iValue);

    Display(iValue);

    return 0;

} // End of main

